"""Маскирование номеров карт и паспортов перед отправкой в модель."""

import re

MASK = "[номер скрыт]"

# \b тут не годится: он Unicode-aware, и «карта4276…» не совпадёт. Границы — по цифрам.
# карта: 13–19 цифр подряд или четыре группы по 4 цифры через пробел/дефис/подчёркивание
_CARD = re.compile(r"(?<!\d)\d{13,19}(?!\d)|(?<!\d)(?:\d{4}[ _-]){3}\d{4}(?!\d)")
# паспорт РФ с пробельной группировкой: 03 15 123456 или 0315 123456
_PASSPORT_GROUPED = re.compile(r"(?<!\d)(?:\d{2}\s\d{2}|\d{4})\s\d{6}(?!\d)")
# 10 цифр подряд — паспорт, только если рядом слово «паспорт»/«серия» (иначе это телефон, ИНН)
_PASSPORT_BARE = re.compile(r"((?:паспорт|серия)\D{0,20})(?<!\d)\d{10}(?!\d)", re.IGNORECASE)


def mask_pii(text: str) -> str:
    text = _CARD.sub(MASK, text)
    text = _PASSPORT_BARE.sub(lambda m: m.group(1) + MASK, text)
    return _PASSPORT_GROUPED.sub(MASK, text)
